// sdks/scripts/dart-client.mjs: the generated Dart visitor client follows the
// widget contract (every native-relevant /v1/widget/* operation has a method,
// browser-only replay routes are left out) and the generator refuses shapes
// it cannot map instead of emitting wrong code. The Dart side is analyzed and
// tested by `dart analyze` / `dart test` in sdks/flutter/clickfix_visitor.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { parse } from 'yaml';
import { renderDartClient } from '../scripts/dart-client.mjs';

// The public mirror ships sdks/ without the backend contract.
const contract = new URL('../../backend/docs/openapi.yaml', import.meta.url);
const mirror = !existsSync(contract);
const generated = (file) => readFile(new URL(`../flutter/clickfix_visitor/lib/src/generated/${file}`, import.meta.url), 'utf8');

test('dart client: one method per native widget operation', { skip: mirror }, async () => {
  const spec = parse(await readFile(contract, 'utf8'));
  const api = await generated('api.dart');
  let count = 0;
  for (const [path, item] of Object.entries(spec.paths)) {
    if (!path.startsWith('/v1/widget/')) continue;
    for (const [method, op] of Object.entries(item)) {
      if (!op?.operationId) continue;
      const tag = `\`${method.toUpperCase()} ${path}\` (\`${op.operationId}\`)`;
      if (/\/replay-policy$|\/sessions(\/|$)/.test(path)) assert.ok(!api.includes(tag), `${tag} is browser-only`);
      else {
        assert.ok(api.includes(tag), `${tag} has a WidgetApi method`);
        count++;
      }
    }
  }
  assert.ok(count >= 15, `expected the widget operations, found ${count}`);
});

test('dart client: generated files are marked and carry no internal references', async () => {
  for (const file of ['api.dart', 'models.dart']) {
    const text = await generated(file);
    assert.match(text, /^\/\/ GENERATED by sdks\/scripts\/generate\.mjs/);
    assert.match(text, /\/\/ dart format off/);
    assert.doesNotMatch(text, /\bCF-\d+/);
  }
});

const mini = (extra = {}) => ({
  paths: {
    '/v1/widget/{public_id}/ping': {
      parameters: [{ name: 'public_id', in: 'path', required: true, schema: { type: 'string' } }],
      post: {
        operationId: 'widgetPing',
        requestBody: { required: true, content: { 'application/json': { schema: { type: 'object', required: ['at'], properties: { at: { type: 'string', format: 'date-time' }, note: { type: ['string', 'null'] } } } } } },
        responses: { 200: { content: { 'application/json': { schema: { type: 'object', properties: { data: { $ref: '#/components/schemas/Pong' } } } } } } },
        ...extra,
      },
    },
  },
  components: { schemas: { Pong: { type: 'object', required: ['ok', 'tags'], properties: { ok: { type: 'boolean' }, tags: { type: 'array', items: { type: 'string' } } } } } },
});

test('dart client: types, nullability and copyWith of request bodies', () => {
  const { models, api } = renderDartClient(mini());
  assert.match(models, /final DateTime at;/);
  assert.match(models, /final String\? note;/);
  assert.match(models, /'note': \?note,/);
  assert.match(models, /PingInput copyWith\(/);
  assert.match(models, /final List<String> tags;/);
  assert.doesNotMatch(models, /Pong copyWith/);
  assert.match(api, /Future<Pong> ping\(\{required PingInput body, bool\? retry\}\)/);
});

test('dart client: unknown shapes fail generation', () => {
  assert.throws(() => renderDartClient(mini({ operationId: 'Ping' })), /operationId must be widget<Name>/);
  assert.throws(() => renderDartClient(mini({ parameters: [{ name: 'X-Other', in: 'header', schema: { type: 'string' } }] })), /header X-Other/);
  assert.throws(() => renderDartClient(mini({ requestBody: { content: { 'text/plain': { schema: { type: 'string' } } } } })), /unsupported request type/);
});

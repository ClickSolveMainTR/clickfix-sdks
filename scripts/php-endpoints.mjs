// Renders sdks/php/src/Endpoints.php from the public contract: one constant per
// operation (method + path), so the hand-written PHP resource classes are checked
// against backend/docs/public-api.yaml by `make sdks-check` and the package's
// EndpointsTest (every constant must be used by a resource).
const METHODS = ['get', 'put', 'post', 'delete', 'patch'];

export function constantName(method, path) {
  const words = path.replace(/^\/v1\/(public-api\/)?/, '').replace(/\{(\w+)\}/g, 'by_$1').split(/[^A-Za-z0-9]+/).filter(Boolean);
  return [method, ...words].join('_').toUpperCase();
}

export function renderPhpEndpoints(spec) {
  const ops = [];
  for (const [path, item] of Object.entries(spec.paths)) {
    if (path.startsWith('/v1/app-context/')) continue; // public but keyless: no SDK resource wraps it
    for (const method of METHODS) {
      const op = item[method];
      if (!op) continue;
      ops.push({ method: method.toUpperCase(), path, id: op.operationId, summary: op.summary ?? '' });
    }
  }
  ops.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
  const lines = ops.map((o) =>
    `    /** ${o.id}: ${o.summary.replace(/\*\//g, '* /')} */\n    public const ${constantName(o.method.toLowerCase(), o.path)} = ['${o.method}', '${o.path}'];`);
  const all = ops.map((o) => `        self::${constantName(o.method.toLowerCase(), o.path)},`);
  return `<?php

declare(strict_types=1);

namespace ClickFix;

/**
 * Generated by sdks/scripts/generate.mjs from backend/docs/public-api.yaml. Do not edit; run \`make sdks\`.
 * Each constant is [method, path]; the resource classes under Resources/ use them, and EndpointsTest
 * fails when an operation of the public contract has no resource method.
 */
final class Endpoints
{
${lines.join('\n')}

    /** @var list<array{0: string, 1: string}> */
    public const ALL = [
${all.join('\n')}
    ];
}
`;
}
